using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using AxamlIdGen.Models;

namespace AxamlIdGen.Emit;

public static class ManifestEmitter
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        Converters = { new JsonStringEnumConverter(JsonNamingPolicy.CamelCase) }
    };

    public static string EmitJson(IEnumerable<AutomationIdOccurrence> occurrences, string repoRoot)
    {
        var ordered = occurrences
            .Where(o => o.FinalId != null)
            .OrderBy(o => o.FinalId, StringComparer.Ordinal)
            .ThenBy(o => RelativePath(o.File, repoRoot), StringComparer.Ordinal)
            .ThenBy(o => o.Line);

        var instance = new SortedDictionary<string, ManifestEntry>(StringComparer.Ordinal);
        var templateScoped = new List<TemplateScopedEntry>();

        foreach (var o in ordered)
        {
            var rel = RelativePath(o.File, repoRoot);
            if (o.Scope == Scope.Instance)
            {
                instance[o.FinalId!] = new ManifestEntry(
                    o.ViewName,
                    o.ControlElementName,
                    rel,
                    o.Line,
                    o.Provenance,
                    o.CollisionResolved
                );
            }
            else
            {
                templateScoped.Add(new TemplateScopedEntry(
                    o.FinalId!,
                    o.Scope,
                    o.TemplateTargetType,
                    o.ControlElementName,
                    rel,
                    o.Line
                ));
            }
        }

        var doc = new ManifestDocument(instance, templateScoped);
        return JsonSerializer.Serialize(doc, JsonOptions) + "\n";
    }

    public static string EmitCSharp(IEnumerable<AutomationIdOccurrence> occurrences, string ns)
    {
        var ids = occurrences
            .Where(o => o.Scope == Scope.Instance && o.FinalId != null)
            .Select(o => o.FinalId!)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(x => x, StringComparer.Ordinal);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by AxamlIdGen. Do not edit by hand.");
        sb.AppendLine("// Source of truth: XAML files containing AutomationProperties.AutomationId.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("public static class AutomationIds");
        sb.AppendLine("{");
        foreach (var id in ids)
        {
            sb.AppendLine($"    public const string {id} = \"{id}\";");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitTypeScript(IEnumerable<AutomationIdOccurrence> occurrences)
    {
        var ids = occurrences
            .Where(o => o.Scope == Scope.Instance && o.FinalId != null)
            .Select(o => o.FinalId!)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(x => x, StringComparer.Ordinal)
            .ToArray();

        var sb = new StringBuilder();
        sb.AppendLine("// AUTO-GENERATED by AxamlIdGen. Do not edit by hand.");
        sb.AppendLine("// Source of truth: XAML files containing AutomationProperties.AutomationId.");
        sb.AppendLine();
        sb.AppendLine("export const AutomationIds = {");
        foreach (var id in ids)
        {
            sb.AppendLine($"    {id}: \"{id}\",");
        }
        sb.AppendLine("} as const;");
        sb.AppendLine();
        sb.AppendLine("export type AutomationIdKey = keyof typeof AutomationIds;");
        return sb.ToString();
    }

    private static string RelativePath(string fullPath, string repoRoot)
    {
        try
        {
            return Path.GetRelativePath(repoRoot, fullPath).Replace('\\', '/');
        }
        catch
        {
            return fullPath.Replace('\\', '/');
        }
    }

    private sealed record ManifestDocument(
        SortedDictionary<string, ManifestEntry> Instance,
        List<TemplateScopedEntry> TemplateScoped);

    private sealed record ManifestEntry(
        string View,
        string Control,
        string File,
        int Line,
        ProvenanceSource Source,
        bool CollisionResolved);

    private sealed record TemplateScopedEntry(
        string Id,
        Scope Scope,
        string? TemplateTargetType,
        string Control,
        string File,
        int Line);
}
